import type { SourceAdapterKind } from "../domain/entities";

export type DefaultSourceCatalogEntry = {
  identityKey: string;
  companyName: string;
  companyType: string;
  industry: string;
  websiteUrl: string;
  adapter: SourceAdapterKind;
  externalKey: string;
  baseUrl: string;
  allowedHosts: string[];
  countryCodes: string[];
  syncIntervalMinutes: number;
};

function mokaSource(input: {
  identityKey: string;
  companyName: string;
  companyType: string;
  industry: string;
  orgId: string;
  mode: "social" | "campus";
  siteId?: string;
  portal?:
    "social-recruitment" | "campus-recruitment" | "apply" | "campus_apply";
}) {
  const portal =
    input.portal ??
    (input.mode === "campus" ? "campus-recruitment" : "social-recruitment");
  const sitePath = input.siteId ? `/${input.siteId}` : "";
  return {
    identityKey: input.identityKey,
    companyName: input.companyName,
    companyType: input.companyType,
    industry: input.industry,
    websiteUrl: `https://app.mokahr.com/${portal}/${input.orgId}${sitePath}`,
    adapter: "moka" as const,
    externalKey: `${input.orgId}|${input.mode}|${input.siteId ?? ""}`,
    baseUrl: "https://api.mokahr.com/",
    allowedHosts: ["api.mokahr.com"],
    countryCodes: ["cn"],
    syncIntervalMinutes: 360,
  };
}

function publicAtsSource(input: {
  identityKey: string;
  companyName: string;
  industry: string;
  adapter: "smartrecruiters" | "greenhouse" | "lever";
  externalKey: string;
}) {
  const configuration = {
    smartrecruiters: {
      websiteHost: "jobs.smartrecruiters.com",
      baseUrl: "https://api.smartrecruiters.com/",
      allowedHost: "api.smartrecruiters.com",
    },
    greenhouse: {
      websiteHost: "job-boards.greenhouse.io",
      baseUrl: "https://boards-api.greenhouse.io/",
      allowedHost: "boards-api.greenhouse.io",
    },
    lever: {
      websiteHost: "jobs.lever.co",
      baseUrl: "https://api.lever.co/",
      allowedHost: "api.lever.co",
    },
  }[input.adapter];
  return {
    identityKey: input.identityKey,
    companyName: input.companyName,
    companyType: "外企",
    industry: input.industry,
    websiteUrl: `https://${configuration.websiteHost}/${input.externalKey}`,
    adapter: input.adapter,
    externalKey: input.externalKey,
    baseUrl: configuration.baseUrl,
    allowedHosts: [configuration.allowedHost],
    countryCodes: ["cn"],
    syncIntervalMinutes: 360,
  } satisfies DefaultSourceCatalogEntry;
}

